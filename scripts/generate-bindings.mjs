#!/usr/bin/env node
/**
 * generate-bindings.mjs — deterministic code generation for the ZK-VOTE
 * protocol manifest (shared/protocol-manifest.json).
 *
 * One schema produces every checked-in binding:
 *   - frontend/src/generated/zkv1.ts
 *   - backend/src/generated/zkv1.ts
 *   - packages/sdk/src/generated/zkv1.ts
 *   - contracts/zkvote-groth16/src/generated/protocol.rs
 *
 * Run `node scripts/generate-bindings.mjs` to (re)generate, or
 * `node scripts/generate-bindings.mjs --check` to verify the checked-in files
 * are current without writing anything. `--root <dir>` is supported so tests
 * can generate into a temporary fixture tree.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = path.resolve(SCRIPT_DIR, "..");
const MANIFEST_REL = "shared/protocol-manifest.json";

const TS_TARGETS = [
  "frontend/src/generated/zkv1.ts",
  "backend/src/generated/zkv1.ts",
  "packages/sdk/src/generated/zkv1.ts",
];
const RS_TARGET = "contracts/zkvote-groth16/src/generated.rs";

function parseArgs(argv) {
  let root = DEFAULT_ROOT;
  let check = false;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") check = true;
    else if (arg === "--root") root = path.resolve(argv[++i]);
    else if (arg.startsWith("--root=")) root = path.resolve(arg.slice(7));
    else throw new Error("usage: generate-bindings.mjs [--check] [--root <dir>]");
  }
  return { root, check };
}

/** Small structural validator — keeps this script zero-dependency. */
function validateManifest(m) {
  const fail = (msg) => {
    throw new Error(`protocol manifest invalid: ${msg}`);
  };
  if (m.schemaVersion !== 1) fail("schemaVersion must be 1");
  if (!m.networks?.testnet?.contractIds) fail("missing testnet contract IDs");
  for (const [name, id] of Object.entries(m.networks.testnet.contractIds)) {
    if (!/^C[A-Z2-7]{55}$/.test(id)) fail(`bad contract id ${name}: ${id}`);
  }
  if (!m.circuits?.vote_v1?.publicSignals?.length) fail("missing vote_v1 public signals");
  const pf = m.proofFormat;
  if (!pf) fail("missing proofFormat");
  if (pf.version !== 1) fail("proofFormat.version must be 1");
  if (pf.totalBytes !== 2 + pf.g1Bytes + pf.g2Bytes + pf.g1Bytes) {
    fail("proofFormat.totalBytes inconsistent with point lengths");
  }
  if (pf.g1Bytes !== 2 * pf.fieldBytes || pf.g2Bytes !== 4 * pf.fieldBytes) {
    fail("point lengths must be 2/4 field elements");
  }
  return m;
}

function json(value) {
  return JSON.stringify(value, null, 2);
}

/**
 * Generate the portable TypeScript binding. It is intentionally dependency
 * free: the same bytes come out in a browser, in Node and in the SDK bundle.
 */
function renderTs(m) {
  const ids = m.networks.testnet.contractIds;
  const signals = Object.fromEntries(
    Object.entries(m.circuits).map(([k, v]) => [k, v.publicSignals]),
  );
  const pf = m.proofFormat;
  const L = [];
  const push = (...lines) => L.push(...lines);

  push(
    "// AUTO-GENERATED by scripts/generate-bindings.mjs — DO NOT EDIT.",
    "// Source: shared/protocol-manifest.json (schemaVersion " + m.schemaVersion + ").",
    "// Regenerate with: node scripts/generate-bindings.mjs",
    "",
    "export const PROTOCOL_SCHEMA_VERSION = " + m.schemaVersion + " as const;",
    "",
    "export const CONTRACT_IDS = " + json(ids) + " as const;",
    "export type ContractIdName = keyof typeof CONTRACT_IDS;",
    "",
    "export const CIRCUIT_IDS = " + json(m.circuitIds) + " as const;",
    "export type KnownCircuitId = (typeof CIRCUIT_IDS)[number];",
    "",
    "/** Canonical public-signal order, index = position. Append-only policy. */",
    "export const PUBLIC_SIGNALS = " + json(signals) + " as const;",
    "export type CircuitId = keyof typeof PUBLIC_SIGNALS;",
    "",
    "export type VoteSignals = typeof PUBLIC_SIGNALS.vote_v1;",
    "export type CommentSignals = typeof PUBLIC_SIGNALS.comment_v2;",
    "",
    "export const NUM_PUBLIC_SIGNALS_BY_CIRCUIT = " +
      json(
        Object.fromEntries(
          Object.entries(signals).map(([k, v]) => [k, v.length]),
        ),
      ) +
      " as const;",
    "",
    "export const NUM_PUBLIC_SIGNALS = " + signals.vote_v1.length + " as const;",
    "export const VK_IC_LENGTH = NUM_PUBLIC_SIGNALS + 1;",
    "",
    "export const PROOF_FORMAT_VERSION = " + pf.version + " as const;",
    "export const FIELD_BYTES = " + pf.fieldBytes + " as const;",
    "export const G1_LEN = " + pf.g1Bytes + " as const;",
    "export const G2_LEN = " + pf.g2Bytes + " as const;",
    "export const HEADER_BYTES = " + pf.headerBytes + " as const;",
    "export const SERIALIZED_PROOF_LEN = " + pf.totalBytes + " as const;",
    "export const PROOF_OFFSETS = " + json(pf.offsets) + " as const;",
    "export const B_COORDINATE_ORDER = " + json(pf.bCoordinateOrder) + " as const;",
    "",
    "export const ProofCurveId = " + json(pf.curveIds) + " as const;",
    "export type ProofCurveId = (typeof ProofCurveId)[keyof typeof ProofCurveId];",
    "",
    "export const PROOF_FORMAT = " + json(pf) + " as const;",
    "export const VK_SHAPE = " + json(m.vkShape) + " as const;",
    "export const ERROR_CODES = " + json(m.errorCodes) + " as const;",
    "",
    "export class ProofFormatError extends Error {",
    "  constructor(message: string) {",
    "    super(message);",
    "    this.name = \"ProofFormatError\";",
    "  }",
    "}",
    "",
    "/** Canonical proof payload: big-endian hex coordinates without the header. */",
    "export interface Zkv1Proof {",
    "  a: string; // 128 hex chars (G1: X || Y)",
    "  b: string; // 256 hex chars (G2: X_c1 || X_c0 || Y_c1 || Y_c0)",
    "  c: string; // 128 hex chars (G1: X || Y)",
    "}",
    "",
    "/** Legacy snarkjs shape, accepted only at the adapter boundary. */",
    "export interface SnarkjsProof {",
    "  pi_a: string[];",
    "  pi_b: string[][];",
    "  pi_c: string[];",
    "  protocol?: string;",
    "  curve?: string;",
    "}",
    "",
    "const HEX_RE = /^(0x)?[0-9a-fA-F]*$/;",
    "",
    "function toFixedHex(value: string, bytes: number, label: string): string {",
    "  if (typeof value !== \"string\" || !HEX_RE.test(value)) {",
    "    throw new ProofFormatError(label + \" must be a hex string\");",
    "  }",
    "  const digits = value.startsWith(\"0x\") ? value.slice(2) : value;",
    "  if (digits.length > bytes * 2) {",
    "    throw new ProofFormatError(label + \" exceeds \" + bytes + \" bytes\");",
    "  }",
    "  return digits.toLowerCase().padStart(bytes * 2, \"0\");",
    "}",
    "",
    "function finiteField(value: string, label: string): string {",
    "  if (typeof value !== \"string\" || value.trim() === \"\") {",
    "    throw new ProofFormatError(label + \" is missing\");",
    "  }",
    "  let n: bigint;",
    "  try {",
    "    n = BigInt(value);",
    "  } catch {",
    "    throw new ProofFormatError(label + \" is not an integer\");",
    "  }",
    "  if (n < 0n) throw new ProofFormatError(label + \" must be non-negative\");",
    "  return n.toString(16).padStart(FIELD_BYTES * 2, \"0\");",
    "}",
    "",
    "function isZeroHex(hex: string): boolean {",
    "  return /^0+$/.test(hex);",
    "}",
    "",
    "/** Serialize a ZKV1 proof to bytes (version || curve || A || B || C). */",
    "export function serializeProofBytes(proof: Zkv1Proof, curve: ProofCurveId = ProofCurveId.Bn254): Uint8Array {",
    "  if (!proof || typeof proof !== \"object\") throw new ProofFormatError(\"Invalid proof: expected an object\");",
    "  const a = toFixedHex(proof.a, G1_LEN, \"proof.a\");",
    "  const b = toFixedHex(proof.b, G2_LEN, \"proof.b\");",
    "  const c = toFixedHex(proof.c, G1_LEN, \"proof.c\");",
    "  if (isZeroHex(a) || isZeroHex(b) || isZeroHex(c)) {",
    "    throw new ProofFormatError(\"Invalid proof: component is the point at infinity\");",
    "  }",
    "  if (curve !== ProofCurveId.Bn254 && curve !== ProofCurveId.Bls12381) {",
    "    throw new ProofFormatError(\"Unknown curve id: \" + curve);",
    "  }",
    "  const out = new Uint8Array(SERIALIZED_PROOF_LEN);",
    "  out[PROOF_OFFSETS.version] = PROOF_FORMAT_VERSION;",
    "  out[PROOF_OFFSETS.curveId] = curve;",
    "  let p = PROOF_OFFSETS.a;",
    "  for (const hex of [a, b, c]) {",
    "    for (let i = 0; i < hex.length; i += 2) out[p++] = parseInt(hex.slice(i, i + 2), 16);",
    "  }",
    "  return out;",
    "}",
    "",
    "/** Deserialize ZKV1 bytes. Validates length, version and curve tag. */",
    "export function deserializeProofBytes(bytes: Uint8Array): { proof: Zkv1Proof; curve: ProofCurveId } {",
    "  if (!(bytes instanceof Uint8Array)) throw new ProofFormatError(\"Expected Uint8Array\");",
    "  if (bytes.length !== SERIALIZED_PROOF_LEN) {",
    "    throw new ProofFormatError(\"Invalid proof length: expected \" + SERIALIZED_PROOF_LEN + \", got \" + bytes.length);",
    "  }",
    "  if (bytes[PROOF_OFFSETS.version] !== PROOF_FORMAT_VERSION) {",
    "    throw new ProofFormatError(\"Unsupported proof format version: \" + bytes[PROOF_OFFSETS.version]);",
    "  }",
    "  const curve = bytes[PROOF_OFFSETS.curveId] as ProofCurveId;",
    "  if (curve !== ProofCurveId.Bn254 && curve !== ProofCurveId.Bls12381) {",
    "    throw new ProofFormatError(\"Unknown curve id: \" + curve);",
    "  }",
    "  const slice = (from: number, len: number): string =>",
    "    Array.from(bytes.subarray(from, from + len), (b) => b.toString(16).padStart(2, \"0\")).join(\"\");",
    "  return {",
    "    proof: {",
    "      a: \"0x\" + slice(PROOF_OFFSETS.a, G1_LEN),",
    "      b: \"0x\" + slice(PROOF_OFFSETS.b, G2_LEN),",
    "      c: \"0x\" + slice(PROOF_OFFSETS.c, G1_LEN),",
    "    },",
    "    curve,",
    "  };",
    "}",
    "",
    "/**",
    " * THE legacy adapter boundary. snarkjs pi_a/pi_b/pi_c (decimal or 0x",
    " * strings) are converted once, here, into the canonical ZKV1 payload.",
    " * G2 c0/c1 pairs are swapped to the Soroban/Ethereum order.",
    " */",
    "export function snarkjsToZkv1(snarkjs: SnarkjsProof): Zkv1Proof {",
    "  if (!snarkjs || !Array.isArray(snarkjs.pi_a) || !Array.isArray(snarkjs.pi_b) || !Array.isArray(snarkjs.pi_c)) {",
    "    throw new ProofFormatError(\"Invalid snarkjs proof shape\");",
    "  }",
    "  const a = finiteField(snarkjs.pi_a[0], \"pi_a[0]\") + finiteField(snarkjs.pi_a[1], \"pi_a[1]\");",
    "  const b =",
    "    finiteField(snarkjs.pi_b[0][1], \"pi_b[0][1]\") +",
    "    finiteField(snarkjs.pi_b[0][0], \"pi_b[0][0]\") +",
    "    finiteField(snarkjs.pi_b[1][1], \"pi_b[1][1]\") +",
    "    finiteField(snarkjs.pi_b[1][0], \"pi_b[1][0]\");",
    "  const c = finiteField(snarkjs.pi_c[0], \"pi_c[0]\") + finiteField(snarkjs.pi_c[1], \"pi_c[1]\");",
    "  return { a: \"0x\" + a, b: \"0x\" + b, c: \"0x\" + c };",
    "}",
    "",
    "/** Reverse adapter, used by the relayer when a snarkjs API must be fed. */",
    "export function zkv1ToSnarkjs(proof: Zkv1Proof): SnarkjsProof {",
    "  const a = toFixedHex(proof.a, G1_LEN, \"proof.a\");",
    "  const b = toFixedHex(proof.b, G2_LEN, \"proof.b\");",
    "  const c = toFixedHex(proof.c, G1_LEN, \"proof.c\");",
    "  const field = (hex: string, start: number): string => BigInt(\"0x\" + hex.slice(start, start + FIELD_BYTES * 2)).toString();",
    "  return {",
    "    pi_a: [field(a, 0), field(a, FIELD_BYTES * 2), \"1\"],",
    "    pi_b: [",
    "      [field(b, FIELD_BYTES * 2), field(b, 0)],",
    "      [field(b, FIELD_BYTES * 6), field(b, FIELD_BYTES * 4)],",
    "      [\"1\", \"0\"],",
    "    ],",
    "    pi_c: [field(c, 0), field(c, FIELD_BYTES * 2), \"1\"],",
    "    protocol: \"groth16\",",
    "    curve: \"bn128\",",
    "  };",
    "}",
    "",
    "/** Encode decimal signal strings as 32-byte big-endian hex, in registry order. */",
    "export function encodePublicSignalsBE(signals: readonly string[]): string[] {",
    "  return signals.map((s) => finiteField(s, \"public signal\"));",
    "}",
    "",
    "export function assertSignalCount(circuit: CircuitId, signals: readonly unknown[]): void {",
    "  const expected = NUM_PUBLIC_SIGNALS_BY_CIRCUIT[circuit];",
    "  if (expected === undefined) throw new ProofFormatError(\"Unknown circuit: \" + circuit);",
    "  if (signals.length !== expected) {",
    "    throw new ProofFormatError(circuit + \" expects \" + expected + \" public signals, got \" + signals.length);",
    "  }",
    "}",
  );
  return L.join("\n") + "\n";
}

function renderRust(m) {
  const pf = m.proofFormat;
  const L = [];
  const push = (...lines) => L.push(...lines);
  push(
    "// AUTO-GENERATED by scripts/generate-bindings.mjs — DO NOT EDIT.",
    "// Source: shared/protocol-manifest.json (schemaVersion " + m.schemaVersion + ").",
    "#![allow(dead_code)]",
    "",
    "pub const PROOF_FORMAT_VERSION: u8 = " + pf.version + ";",
    "pub const FIELD_BYTES: usize = " + pf.fieldBytes + ";",
    "pub const G1_LEN: usize = " + pf.g1Bytes + ";",
    "pub const G2_LEN: usize = " + pf.g2Bytes + ";",
    "pub const HEADER_BYTES: usize = " + pf.headerBytes + ";",
    "pub const SERIALIZED_PROOF_LEN: usize = " + pf.totalBytes + ";",
    "pub const A_OFFSET: usize = " + pf.offsets.a + ";",
    "pub const B_OFFSET: usize = " + pf.offsets.b + ";",
    "pub const C_OFFSET: usize = " + pf.offsets.c + ";",
    "pub const CURVE_BN254: u8 = " + pf.curveIds.Bn254 + ";",
    "pub const CURVE_BLS12381: u8 = " + pf.curveIds.Bls12381 + ";",
    "",
    "pub const VOTE_PUBLIC_SIGNALS: [&str; " + m.circuits.vote_v1.publicSignals.length + "] = [",
  );
  for (const s of m.circuits.vote_v1.publicSignals) push('    "' + s + '",');
  push(
    "];",
    "pub const NUM_PUBLIC_SIGNALS: u32 = " + m.circuits.vote_v1.publicSignals.length + ";",
    "pub const VOTE_CIRCUIT_IC_LEN: u32 = NUM_PUBLIC_SIGNALS + 1;",
  );
  return L.join("\n") + "\n";
}

function main() {
  const { root, check } = parseArgs(process.argv.slice(2));
  const manifest = validateManifest(
    JSON.parse(fs.readFileSync(path.join(root, MANIFEST_REL), "utf-8")),
  );
  const outputs = new Map();
  const ts = renderTs(manifest);
  for (const target of TS_TARGETS) outputs.set(target, ts);
  outputs.set(RS_TARGET, renderRust(manifest));

  let dirty = 0;
  for (const [rel, content] of outputs) {
    const abs = path.join(root, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf-8") : null;
    if (current === content) continue;
    dirty += 1;
    if (check) {
      console.error("STALE GENERATED FILE: " + rel);
    } else {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content, "utf-8");
      console.log("generated " + rel);
    }
  }
  if (check) {
    if (dirty) {
      console.error("\nGenerated bindings are stale. Run: node scripts/generate-bindings.mjs");
      process.exitCode = 1;
    } else {
      console.log("Generated bindings are up to date.");
    }
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();

export { validateManifest, renderTs, renderRust, parseArgs };
